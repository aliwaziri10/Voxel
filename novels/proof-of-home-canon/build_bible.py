"""
build_bible.py - reads canon_data.py and writes the two files the Voxel Novel
workflow and the pipeline read:
  story_bibles/larkmere.json          cast, fixed facts, and the whole-book beat map
  novels/proof-of-home/beat_map.md    the same plan, human-readable (the pipeline's outline file)

Run from this folder: python3 build_bible.py
Edit canon_data.py, never the generated files. Re-run this after any canon change.
The GitHub workflow "Build Proof of Home canon" does this by itself on every push.
The generator reuses the beat map when its chapter count matches the number of
chapters requested, so the chapters are written from this plan.
"""
import json
import os
import re
import sys

import build_canon as bc
import canon_data as c

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
BIBLE_PATH = os.path.join(ROOT, "story_bibles", f"{c.SERIES_SLUG}.json")
BOOK_DIR = os.path.join(ROOT, "novels", "proof-of-home")
EXTRA_BANNED = re.compile(r"\barc\b|\bseries\b", re.IGNORECASE)

VOICE = {
    "Sarah Quill": " When she holds the point of view the voice is warm and sensory, quick to notice heat, hands, flour and rising dough, and her comparisons come from baking.",
    "Jack Mercer": " When he holds the point of view the voice is dry, spare and watchful, and his comparisons come from water, lines, current and the tiller. Baking comparisons stay out of his chapters and water comparisons stay out of hers.",
}

REASON = {
    "public": "other people are close and watching",
    "magic": "the ferry or the bread's magic gets in the way",
    "alone": "nobody stops them and they hold back anyway",
    "weather": "the weather forces them together or breaks the moment",
}


def check(text, label):
    m = bc.BANNED.search(text) or EXTRA_BANNED.search(text)
    if m:
        sys.exit(f"banned text in {label}: {m.group(0)!r}")


def characters():
    out = {}
    for name, p in c.CAST.items():
        out[name] = f"{bc.cap(p['role'])}, {p['age']}. {p['desc']}{VOICE.get(name, '')}"
    return out


def plot_facts():
    facts = list(c.WORLD_RULES)
    facts.append(
        f"{c.TOWN} is a small fictional lakeside town on {c.LAKE}. Sarah's bakery is on Lantern Street. "
        "Jack pilots the ferry Heron across the lake. Odalys Pike runs the Lamplight Inn. "
        "Gideon Teague lights the harbor lanterns at dusk."
    )
    facts.append("Odd chapters are told from Sarah's point of view and even chapters from Jack's, in close third person, past tense.")
    for r in c.ROMANCE_RULES:
        if r.startswith("Do not kiss before"):
            continue
        facts.append("Writing rule: " + r)
    return facts


def sub_beats(ch):
    n = ch["n"]
    pov = bc.NAMES[ch["pov"]]
    if n < c.KISS_CHAPTER:
        kiss = " They do not kiss in this chapter."
    elif n == c.KISS_CHAPTER:
        kiss = " This is the first kiss."
    else:
        kiss = " They have already kissed, and the wanting is bigger than before, not smaller."
    if n == c.CHAPTER_COUNT:
        kiss += " This is the full release of everything held back."
    out = [
        {"type": "plot_beat", "detail": ch["beat"]},
        {"type": "forced_closeness_beat",
         "detail": f"Touch level {ch['rung']} of 10 ({c.TOUCH_LADDER[ch['rung']]}). Place: {ch['space']}. "
                   f"Contact: {ch['contact']}. How they hold back: {ch['restraint']}. "
                   f"Why they cannot act: {REASON[ch['reason']]}. Stay inside the body: the held breath, "
                   f"the stillness, the effort of staying still. Sensual, never explicit.{kiss}"},
        {"type": "interior_beat",
         "detail": f"Point of view: {pov}, close third person, past tense. Season: {ch['season']}. "
                   f"The feeling to leave in the reader: {ch['ache']}."},
        {"type": "bread_magic_beat", "detail": bc.cap(ch["bread"]) + "."},
    ]
    if n > 1:
        prev = c.CHAPTERS[n - 2]
        out.append({"type": "callback_beat",
                    "detail": f"The last chapter left off in this feeling: {prev['ache']}."})
    for s in bc.hidden_for(n):
        out.append({"type": "secret_beat", "detail": s})
    return out


def beat_map_md():
    out = [
        f"# Beat map: {c.BOOK_TITLE}", "",
        "Generated by build_bible.py from canon_data.py. Do not edit by hand. Edit canon_data.py and re-run.", "",
        f"{c.CHAPTER_COUNT} chapters. First kiss in chapter {c.KISS_CHAPTER}. Sarah holds the point of view in odd "
        "chapters and Jack in even chapters. The longing rises to the last chapter and is released there.", "",
    ]
    for ch in c.CHAPTERS:
        n = ch["n"]
        out.append(f"## Chapter {n} ({bc.NAMES[ch['pov']]}, {ch['season']}, touch {ch['rung']} of 10)")
        out.append(f"Happens: {ch['beat']}")
        out.append(f"Place: {ch['space']}. Contact: {ch['contact']}. Holds back: {ch['restraint']}.")
        out.append(f"Why they cannot act: {REASON[ch['reason']]}. Ache: {ch['ache']}.")
        out.append(f"Bread: {ch['bread']}.")
        for s in bc.hidden_for(n):
            out.append(f"Secret: {s}")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    bible = {
        "series_slug": c.SERIES_SLUG,
        "characters": characters(),
        "visual_style": "",
        "plot_facts": plot_facts(),
        "books": [],
        "book_beat_maps": {
            c.BOOK_TITLE: [{"chapter": ch["n"], "sub_beats": sub_beats(ch)} for ch in c.CHAPTERS]
        },
    }
    # Writing rules are instructions to the writer and name banned phrases on purpose,
    # so only the story content is scanned.
    scanned = dict(bible)
    scanned["plot_facts"] = [f for f in bible["plot_facts"] if not f.startswith("Writing rule:")]
    check(json.dumps(scanned, ensure_ascii=False), "story bible")
    md = beat_map_md()
    check(md, "beat_map.md")
    os.makedirs(os.path.dirname(BIBLE_PATH), exist_ok=True)
    os.makedirs(BOOK_DIR, exist_ok=True)
    with open(BIBLE_PATH, "w") as f:
        json.dump(bible, f, indent=2, ensure_ascii=False)
        f.write("\n")
    with open(os.path.join(BOOK_DIR, "beat_map.md"), "w") as f:
        f.write(md)
    print(f"wrote {BIBLE_PATH} and beat_map.md for {c.CHAPTER_COUNT} chapters")


if __name__ == "__main__":
    main()
